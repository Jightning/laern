#!/usr/bin/env node
/* Prints the two study artefacts that are now derived rather than written.
 *
 *   node tools/gen-materials.mjs [--check] [course …]
 *
 * `problems.md` is the drill bank, printed. `checklist.md` is the question
 * surface plus the concepts, printed. A hand-kept index drifts from the course;
 * a derived one cannot, which is the whole of T20 — and T21 says a generated
 * file is never edited, so --check fails the build if one has been.
 *
 * A course with no drills/ folder has not migrated yet and is left alone.
 */
import { readdirSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadCourse } from "./lib/load.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const COURSES = join(ROOT, "courses");
const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const wanted = args.filter(a => !a.startsWith("--"));

const BANNER = "<!-- generated by tools/gen-materials.mjs — do not edit -->";
const strip = h => String(h).replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

function problems(C) {
  const out = [BANNER, "", `# ${C.code} — Drill problems`, "",
    "Different purpose from the question blocks on the site. Those give one question",
    "per question type, for coverage. These repeat the same procedures, for speed and",
    "accuracy under time pressure.", "",
    "Work them with a pencil. Solutions follow each set.", ""];

  for (const key of Object.keys(C.drills).sort()) {
    const items = C.drills[key].items || [];
    const term = (C.concepts[key] || {}).term || key;
    out.push("---", "", `## ${term}`, "");
    items.forEach((it, i) => out.push(`${i + 1}. ${strip(it.stem)}`));
    out.push("", "**Solutions**", "");
    items.forEach((it, i) => {
      const steps = (it.steps || []).map(strip).join(" → ");
      out.push(`${i + 1}. ${steps ? steps + " → " : ""}**${strip(it.answer)}**`);
    });
    out.push("");
  }
  return out.join("\n");
}

function checklist(C) {
  const out = [BANNER, "", `# ${C.code} — Mastery checklist`, "",
    "Every line is something you must be able to do, phrased so the honest answer is",
    "yes or no. Question types come from the site's quizzes; concepts come from the",
    "drill bank, where a tick means durable rather than answered once.", ""];

  for (const s of C.sections) {
    out.push(`## ${s.num} ${s.title}`, "");
    s.subs.forEach((u, k) => {
      const n = `${s.num}.${k + 1}`;
      for (const q of u.quiz || [])
        out.push(`- [ ] ${q.type} — [${n}](../index.html#${u.id})`);
    });
    out.push("");
  }

  const keys = Object.keys(C.drills).sort();
  if (keys.length) {
    out.push("## Concepts held over time", "");
    for (const k of keys)
      out.push(`- [ ] ${(C.concepts[k] || {}).term || k} — durable, not merely answered ` +
               `([drill](../index.html#/${C.id}/c/${k}))`);
    out.push("");
  }
  return out.join("\n");
}

const ids = readdirSync(COURSES, { withFileTypes: true })
  .filter(d => d.isDirectory() && !d.name.startsWith("_")).map(d => d.name)
  .filter(n => !wanted.length || wanted.includes(n));

let stale = 0, wrote = 0;
for (const id of ids) {
  const { course: C } = loadCourse(join(COURSES, id));
  if (!Object.keys(C.drills || {}).length) continue;   /* not migrated yet */
  C.id = id;

  for (const [name, body] of [["problems.md", problems(C)], ["checklist.md", checklist(C)]]) {
    const path = join(COURSES, id, "materials", name);
    const now = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (now === body) continue;
    if (CHECK) {
      console.log(`  ✗ ${id}/materials/${name} does not match its source — it is generated (T21)`);
      stale++;
    } else { writeFileSync(path, body); wrote++; }
  }
}

if (CHECK) {
  console.log(stale ? `FAIL ${stale} generated file(s) edited by hand` : "ok   generated materials match");
  process.exit(stale ? 1 : 0);
}
console.log(`wrote ${wrote} file(s)`);
